export function intlLocale(locale?: Locale) {
  const selected = locale || (typeof document !== "undefined" && document.documentElement.lang === "en" ? "en" : "ar");
  return selected === "en" ? "en-US" : "ar-SA";
}

export function confirmInCurrentLanguage(arabicMessage: string, englishMessage: string) {
  const locale = typeof document !== "undefined" && document.documentElement.lang === "en" ? "en" : "ar";
  return window.confirm(locale === "en" ? englishMessage : arabicMessage);
}

const translatedAttributes = ["aria-label", "title", "placeholder", "alt", "data-tooltip"];

export function applyLocaleToDocument(locale: Locale) {
  if (typeof document === "undefined") return;
  const root = document.documentElement;
  root.lang = locale;
  root.dir = locale === "ar" ? "rtl" : "ltr";
  root.dataset.locale = locale;
  const body = document.body;
  const walker = document.createTreeWalker(body, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || parent.closest("script, style, code, pre, [data-no-translate]")) continue;
    if (node.nodeValue) node.nodeValue = translateValue(node.nodeValue, locale);
  }
  body.querySelectorAll<HTMLElement>(translatedAttributes.map((attribute) => `[${attribute}]`).join(",")).forEach((element) => {
    for (const attribute of translatedAttributes) {
      const value = element.getAttribute(attribute);
      if (value) element.setAttribute(attribute, translateValue(value, locale));
    }
  });
}





